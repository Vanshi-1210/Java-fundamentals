public class DataTypesExample {
    public static void main(String[] args) {

        // Integer types
        int age = 25;
        long worldPopulation = 8000000000L;

        // Floating-point types
        float temperature = 36.5f;
        double bankBalance = 10500.75;

        // Character type
        char grade = 'A';

        // Boolean type
        boolean isLoggedIn = true;

        // Byte type (small range, e.g., memory-efficient storage)
        byte numberOfDaysInWeek = 7;

        // Short type (moderate range)
        short year = 2026;

        // String (non-primitive, but commonly used)
        String studentName = "Rahul";

        // Display values
        System.out.println("Age: " + age);
        System.out.println("World Population: " + worldPopulation);
        System.out.println("Temperature: " + temperature);
        System.out.println("Bank Balance: " + bankBalance);
        System.out.println("Grade: " + grade);
        System.out.println("Is Logged In: " + isLoggedIn);
        System.out.println("Days in Week: " + numberOfDaysInWeek);
        System.out.println("Year: " + year);
        System.out.println("Student Name: " + studentName);
    }
}
